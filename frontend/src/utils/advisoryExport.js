/**
 * Generates formatted WhatsApp text message and opens WhatsApp URL
 */
export function shareToWhatsApp(data) {
  const lang = data.language || "en";
  const t = EXPORT_TRANSLATIONS[lang] || EXPORT_TRANSLATIONS.en;
  const isStage = Boolean(data.isStage);

  let msg = `🌿 *${isStage ? t.stageReportTitle : t.reportTitle}*\n`;
  msg += `🌾 *${t.crop}:* ${data.crop || "—"}\n`;

  if (isStage) {
    msg += `🌱 *${t.stage}:* ${data.condition || data.phase || "—"}\n`;
    if (data.subStage) msg += `📍 *${t.subStage}:* ${data.subStage}\n`;
    if (data.daysToHarvest) msg += `⏳ *${t.daysToHarvest}:* ${data.daysToHarvest}\n`;
  } else {
    msg += `🦠 *${t.condition}:* ${data.condition || "—"}\n`;
    if (data.severity) msg += `⚠️ *${t.severity}:* ${data.severity}\n`;
  }

  msg += `---------------------------------\n`;

  if (data.diagnosis) {
    msg += `🔍 *${t.diagnosisHeader}:*\n${stripHtml(data.diagnosis)}\n\n`;
  }
  if (data.treatment) {
    msg += `💡 *${t.treatmentHeader}:*\n${stripHtml(data.treatment)}\n\n`;
  }
  if (data.irrigation) {
    msg += `💧 *${t.irrigationHeader}:*\n${stripHtml(data.irrigation)}\n\n`;
  }
  if (data.fertilizer) {
    msg += `🌱 *${t.fertilizerHeader}:*\n${stripHtml(data.fertilizer)}\n\n`;
  }
  if (data.organic_tip) {
    msg += `🌿 *${t.organicHeader}:*\n${stripHtml(data.organic_tip)}\n\n`;
  }
  if (data.pestWatch) {
    msg += `🛡️ *${t.pestWatchHeader}:*\n${stripHtml(data.pestWatch)}\n\n`;
  }
  if (data.priorityAction) {
    msg += `⚡ *${t.priorityHeader}:*\n${stripHtml(data.priorityAction)}\n\n`;
  }

  msg += `---------------------------------\n`;
  msg += `🌾 ${t.footerNotice}`;

  const url = "https://api.whatsapp.com/send?text=" + encodeURIComponent(msg);
  window.open(url, "_blank");
}

function formatAdvisoryHtml(text) {
  if (!text) return "—";
  if (text.includes("<ul") || text.includes("<li") || text.includes("<p")) {
    return text;
  }
  const lines = text.split("\n").map(l => l.trim()).filter(Boolean);
  if (lines.length > 1) {
    return "<ol>" + lines.map(l => `<li>${l.replace(/^[-*•\d+.]\s*/, "")}</li>`).join("") + "</ol>";
  }
  return `<p>${text}</p>`;
}

